import 'dotenv/config';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import express from 'express';
import request from 'supertest';
import { prisma } from '../src/shared/utils/prisma';
import { requestRefund, completeRefund, refundOverview } from '../src/modules/reservation/refund.service';
import { previewRequest, reviewRequest } from '../src/modules/reservation/correction-approval.service';
import { approvalInbox, approvalCount, approvalDetail } from '../src/modules/reservation/approval-inbox.service';
import { correctBooking } from '../src/modules/reservation/recovery.service';
import { recordPayment } from '../src/modules/payment/payment.service';
import { dailyOverview } from '../src/modules/reports/daily-overview.service';
import reservationRoutes from '../src/modules/reservation/reservation.routes';
import { generateAccessToken } from '../src/shared/utils/jwt';
import { refundInbox, refundInboxCount } from '../src/modules/reservation/refund-inbox.service';

async function main() {
  assert(['localhost', '127.0.0.1'].includes(new URL(process.env.DATABASE_URL!).hostname));
  const code = `refund-${randomUUID().slice(0, 8)}`;
  const hotel = await prisma.property.create({ data: { propertyCode: code, propertyName: 'Refund fixture', businessName: 'Test', country: 'Ghana', propertyType: 'Hotel' } });
  let ids: number[] = [];
  let otherHotelId: number | undefined;
  try {
    const roles = await prisma.role.findMany({ where: { roleName: { in: ['Manager', 'Receptionist'] } } });
    const users = [];
    for (const role of roles) users.push(await prisma.user.create({ data: { propertyId: hotel.propertyId, roleId: role.roleId, fullName: role.roleName, username: `${code}-${role.roleName}`, passwordHash: 'no-login-fixture' } }));
    ids = users.map(user => user.userId);
    const m = { propertyId: hotel.propertyId, userId: users.find(u => u.roleId === roles.find(r => r.roleName === 'Manager')!.roleId)!.userId }, r = { propertyId: hotel.propertyId, userId: users.find(u => u.userId !== m.userId)!.userId };
    const res = await prisma.reservation.create({ data: { propertyId: hotel.propertyId, confirmationCode: code, status: 'Cancelled', checkInDate: new Date('2030-01-01'), checkOutDate: new Date('2030-01-02'), totalAmount: 200, amountPaid: 200, refundDue: 200, refundStatus: 'Pending', payments: { create: { propertyId: hotel.propertyId, amount: 200, paymentMethod: 'Cash', receivedBy: r.userId } } }, include: { payments: true } });
    const input = { paymentId: res.payments[0].paymentId, amount: 50, reason: 'Guest cancelled. A partial refund is due.' };
    const p = await requestRefund(r, res.reservationId, { ...input, preview: true });
    const req: any = await requestRefund(r, res.reservationId, { ...input, expectedVersion: (p as any).version });
    assert.equal(req.status, 'Pending');
    assert.equal((await refundInbox(r, { status: 'Pending' })).items[0].requestId, req.requestId);
    assert.equal((await refundInboxCount(r)).ready, 0);
    assert.equal((await approvalDetail(m, req.requestId)).needsReview, false);
    await assert.rejects(completeRefund(m, req.requestId, { method: 'Cash', reference: 'CASH-001', moneyReturned: true }), /approve/);
    await assert.rejects(completeRefund(r, req.requestId, { method: 'Cash', reference: 'CASH-001', moneyReturned: true }), /approve/);
    await assert.rejects(reviewRequest(r, req.requestId, { decision: 'approve', expectedVersion: req.expectedVersion }), /manager/);
    const mp = await previewRequest(m, req.requestId);
    await reviewRequest(m, req.requestId, { decision: 'approve', expectedVersion: mp.version });
    assert.equal(await prisma.refund.count({ where: { reservationId: res.reservationId } }), 0);
    assert.equal(Number((await prisma.reservation.findUniqueOrThrow({ where: { reservationId: res.reservationId } })).amountPaid), 200);
    assert.equal((await approvalCount(m)).toReturn, 1);
    assert.equal((await approvalInbox(m, { status: 'ToReturn' })).items[0].requestId, req.requestId);
    assert.equal((await approvalInbox(m, { status: 'History' })).items.length, 0);
    const queue = await refundInbox(r, { search: code });
    assert.equal(queue.items[0].requestId, req.requestId);
    assert.equal(queue.counts.ready, 1);
    assert.equal(queue.pagination.total, 1);
    assert.equal((await refundInboxCount(r)).ready, 1);
    assert.equal((await refundInbox(r, { search: 'no-such-fixture' })).items.length, 0);
    await assert.rejects(refundInbox(r, { limit: 51 }), /pagination/);
    await assert.rejects(refundInbox(r, { status: 'Unknown' }), /Choose/);
    const otherHotel = await prisma.property.create({ data: { propertyCode: `${code}-other`, propertyName: 'Other refund fixture', businessName: 'Test', country: 'Ghana', propertyType: 'Hotel' } });
    otherHotelId = otherHotel.propertyId;
    const otherStaff = await prisma.user.create({ data: { propertyId: otherHotel.propertyId, roleId: roles.find(role => role.roleName === 'Receptionist')!.roleId, username: `${code}-other`, fullName: 'Other receptionist', passwordHash: 'no-login-fixture' } });
    ids.push(otherStaff.userId);
    const other = { userId: otherStaff.userId, propertyId: otherHotel.propertyId };
    assert.equal((await refundInboxCount(other)).ready, 0);
    assert.equal((await refundInbox(other, { search: code })).items.length, 0);
    await prisma.user.update({ where: { userId: r.userId }, data: { isActive: false } });
    await assert.rejects(refundInbox(r, {}), /staff/);
    await assert.rejects(refundInboxCount(r), /staff/);
    await assert.rejects(completeRefund(r, req.requestId, { method: 'Cash', reference: 'CASH-001', moneyReturned: true }), /staff/);
    await prisma.user.update({ where: { userId: r.userId }, data: { isActive: true } });
    await assert.rejects(completeRefund({ ...r, propertyId: hotel.propertyId + 99999 }, req.requestId, { method: 'Cash', reference: 'CASH-001', moneyReturned: true }), /staff|found/);
    await assert.rejects(completeRefund(r, req.requestId, { method: 'Paystack', reference: 'PROVIDER-001', moneyReturned: true }), /Paystack/);
    await assert.rejects(completeRefund(m, req.requestId, { method: 'Cash', reference: 'CASH-001', moneyReturned: false }), /Confirm/);
    const returns = await Promise.all([completeRefund(r, req.requestId, { method: 'Cash', reference: 'CASH-001', moneyReturned: true, amount: 999 }), completeRefund(r, req.requestId, { method: 'Cash', reference: 'CASH-001', moneyReturned: true })]);
    assert.equal(returns[0].refundId, returns[1].refundId);
    assert.equal(Number(returns[0].amount), 50);
    assert.equal(returns[0].returnedBy, r.userId);
    assert.equal(returns[0].returnedByName, 'Receptionist');
    const reviewed = await prisma.correctionRequest.findUniqueOrThrow({ where: { requestId: req.requestId } });
    assert.equal(reviewed.reviewedBy, m.userId);
    assert.equal(reviewed.status, 'Completed');
    assert.equal(await prisma.refund.count({ where: { reservationId: res.reservationId } }), 1);
    const paid = await prisma.payment.findUniqueOrThrow({ where: { paymentId: input.paymentId } });
    assert.equal(paid.status, 'Completed'); assert.equal(Number(paid.amount), 200);
    let updated = await prisma.reservation.findUniqueOrThrow({ where: { reservationId: res.reservationId } });
    assert.equal(Number(updated.amountPaid), 150); assert.equal(Number(updated.refundDue), 150); assert.equal(updated.status, 'Cancelled');
    assert.equal((await approvalCount(m)).actionRequired, 0);
    assert.equal((await approvalInbox(m, { status: 'Completed' })).items.length, 1);
    assert.equal((await refundInboxCount(r)).ready, 0);
    assert.equal((await refundInbox(r, { status: 'History' })).items[0].refund?.returnedBy, r.userId);
    await assert.rejects(requestRefund(r, res.reservationId, { ...input, amount: 151, preview: true }), /exceeds/);
    const p2: any = await requestRefund(r, res.reservationId, { ...input, amount: 150, preview: true });
    const req2: any = await requestRefund(r, res.reservationId, { ...input, amount: 150, expectedVersion: p2.version });
    await assert.rejects(requestRefund(r, res.reservationId, { ...input, amount: 1, preview: true }), /exceeds/);
    const pp = await previewRequest(m, req2.requestId);
    await reviewRequest(m, req2.requestId, { decision: 'approve', expectedVersion: pp.version });
    await assert.rejects(completeRefund(m, req2.requestId, { method: 'Cash', reference: 'CASH-001', moneyReturned: true }), /reference/);
    await assert.rejects(completeRefund(r, req2.requestId, { method: 'Cash', reference: 123, moneyReturned: true }), /reference/);
    const blankReturns = await Promise.all([
      completeRefund(r, req2.requestId, { method: 'Cash', moneyReturned: true }),
      completeRefund(r, req2.requestId, { method: 'Cash', reference: '   ', moneyReturned: true }),
    ]);
    assert.equal(blankReturns[0].reference, null);
    assert.equal(blankReturns[0].refundId, blankReturns[1].refundId);
    updated = await prisma.reservation.findUniqueOrThrow({ where: { reservationId: res.reservationId } });
    assert.equal(Number(updated.amountPaid), 0); assert.equal(Number(updated.refundDue), 0); assert.equal(updated.refundStatus, 'Processed');
    assert.equal((await refundOverview(r, res.reservationId)).returnedTotal, 200);
    await assert.rejects(correctBooking(res.reservationId, m, { action: 'restore', reason: 'Guest requested their reservation restored.', preview: true }), /refunded/);
    await assert.rejects(refundOverview({ ...m, propertyId: hotel.propertyId + 99999 }, res.reservationId), /staff|found/);
    const app = express(); app.use(express.json()); app.use('/api/reservations', reservationRoutes);
    const token = generateAccessToken({ ...r, roleId: roles.find(role => role.roleName === 'Receptionist')!.roleId, username: 'fixture' });
    assert.equal((await request(app).get('/api/reservations/refund-inbox').set('Authorization', `Bearer ${token}`)).status, 200);
    assert.equal((await request(app).get('/api/reservations/refund-inbox/count').set('Authorization', `Bearer ${token}`)).body.data.ready, 0);
    assert.equal((await request(app).get('/api/reservations/refund-inbox')).status, 401);
    assert.equal((await request(app).post(`/api/reservations/refund-requests/${req.requestId}/complete`).set('Authorization', `Bearer ${token}`).send({ method: 'Cash', reference: 'CASH-001', moneyReturned: true })).status, 200);
    assert.equal((await request(app).post(`/api/reservations/${res.reservationId}/refund`).set('Authorization', `Bearer ${token}`)).status, 400);
    // Active overpayment returns only the credit; follow-up payments reconcile net ledger.
    const active = await prisma.reservation.create({ data: { propertyId: hotel.propertyId, confirmationCode: `${code}-active`, status: 'Confirmed', checkInDate: new Date('2030-01-01'), checkOutDate: new Date('2030-01-02'), totalAmount: 200, amountPaid: 250, refundDue: 50, refundStatus: 'Pending', payments: { create: { propertyId: hotel.propertyId, amount: 250, paymentMethod: 'Cash' } } }, include: { payments: true } });
    const a = { paymentId: active.payments[0].paymentId, amount: 50, reason: 'Guest overpaid the booking total.' };
    const ap: any = await requestRefund(m, active.reservationId, { ...a, preview: true });
    const ar: any = await requestRefund(m, active.reservationId, { ...a, expectedVersion: ap.version });
    await reviewRequest(m, ar.requestId, { decision: 'approve', expectedVersion: ap.version });
    const secondBlank = await completeRefund(m, ar.requestId, { method: 'Cash', reference: '', moneyReturned: true });
    assert.equal(secondBlank.reference, null);
    assert.notEqual(secondBlank.refundId, blankReturns[0].refundId);
    await prisma.reservation.update({ where: { reservationId: active.reservationId }, data: { totalAmount: 220 } });
    await recordPayment({ reservationId: active.reservationId, amount: 20, paymentMethod: 'Cash', receivedBy: r.userId });
    assert.equal(Number((await prisma.reservation.findUniqueOrThrow({ where: { reservationId: active.reservationId } })).amountPaid), 220);
    const report = await dailyOverview(m.userId, m.propertyId);
    assert.equal(report.refundsReturned, 250);
    console.log('PASS: manager-only approval, receptionist completion, fixed approved amount, disabled/foreign staff rejection, provider confirmation, exact return records, idempotency/concurrency, balance limits, preserved payments and daily refunds.');
  } finally {
    await prisma.refund.deleteMany({ where: { propertyId: hotel.propertyId } });
    await prisma.auditLog.deleteMany({ where: { userId: { in: ids } } });
    await prisma.property.delete({ where: { propertyId: hotel.propertyId } });
    if (otherHotelId) await prisma.property.delete({ where: { propertyId: otherHotelId } });
    await prisma.$disconnect();
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
